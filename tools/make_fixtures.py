#!/usr/bin/env python3
"""Generate synthetic fixtures for surge's test suite.

The GGUF/safetensors/tokenizer generators below are stdlib-only (struct).
The op fixture generators need numpy (--ops) and mlx + mlx_lm (--hybrid);
run those with the dsv4-venv interpreter, which has both:

    /Users/macmini/models/dsv4-venv/bin/python tools/make_fixtures.py --ops
    /Users/macmini/models/dsv4-venv/bin/python tools/make_fixtures.py --hybrid

Run once at authoring time; the produced binaries are committed to
tests/fixtures/ and are not regenerated by the build.
"""
import json
import pathlib
import struct
import sys

GGUF_MAGIC = b"GGUF"
GGUF_VERSION = 3
ALIGNMENT = 32

# sg_gguf_kv_type values, must match the enum in surge.h. Prefixed KV_ to
# keep them distinct from the sg_tensor_type values below, which use the same
# names for different numbers (KV_F32 is 6, TT_F32 is 0).
KV_I32 = 5
KV_F32 = 6
KV_BOOL = 7
KV_U32 = 4
KV_STR = 8
KV_ARR = 9

# sg_tensor_type values, must match the enum in surge.h.
TT_F32 = 0
TT_Q8_0 = 8


def _str(s: str) -> bytes:
    b = s.encode("utf-8")
    return struct.pack("<Q", len(b)) + b


def _kv_str(key: str, value: str) -> bytes:
    return _str(key) + struct.pack("<I", KV_STR) + _str(value)


def _kv_u32(key: str, value: int) -> bytes:
    return _str(key) + struct.pack("<I", KV_U32) + struct.pack("<I", value)


def _kv_i32(key: str, value: int) -> bytes:
    return _str(key) + struct.pack("<I", KV_I32) + struct.pack("<i", value)


def _kv_bool(key: str, value: bool) -> bytes:
    return _str(key) + struct.pack("<I", KV_BOOL) + struct.pack("<B", 1 if value else 0)


def _kv_arr_u32(key: str, values: list) -> bytes:
    out = _str(key) + struct.pack("<I", KV_ARR) + struct.pack("<I", KV_U32)
    out += struct.pack("<Q", len(values))
    for v in values:
        out += struct.pack("<I", v)
    return out


def _kv_f32(key: str, value: float) -> bytes:
    return _str(key) + struct.pack("<I", KV_F32) + struct.pack("<f", value)


def _kv_arr_str(key: str, values: list) -> bytes:
    out = _str(key) + struct.pack("<I", KV_ARR) + struct.pack("<I", KV_STR)
    out += struct.pack("<Q", len(values))
    for v in values:
        out += _str(v)
    return out


def _tensor_info(name: str, ttype: int, dims: list, offset: int) -> bytes:
    out = _str(name)
    out += struct.pack("<I", len(dims))
    for d in dims:
        out += struct.pack("<Q", d)
    out += struct.pack("<I", ttype)
    out += struct.pack("<Q", offset)
    return out


def write_mini_gguf(path: str) -> None:
    """Write the small GGUF v3 fixture used by tests/test_gguf.c.

    Metadata: general.architecture="qwen3_5" (str),
    qwen3_5.block_count=2 (u32), test.arr=[1,2,3] (u32 array),
    test.i32=-42 (i32), test.bool=true (bool).
    Tensors: t.f32 f32[4] = [1.0, 2.0, 3.0, 4.0];
    t.q8 Q8_0[32], one block: f16 scale 0.5 + int8 0..31.
    """
    kvs = [
        _kv_str("general.architecture", "qwen3_5"),
        _kv_u32("qwen3_5.block_count", 2),
        _kv_arr_u32("test.arr", [1, 2, 3]),
        _kv_i32("test.i32", -42),
        _kv_bool("test.bool", True),
    ]

    f32_nbytes = 4 * 4  # t.f32: f32[4]
    q8_nbytes = 34  # t.q8: Q8_0[32] = 1 block (2-byte f16 scale + 32 int8)

    off_f32 = 0
    off_q8 = ((off_f32 + f32_nbytes + ALIGNMENT - 1) // ALIGNMENT) * ALIGNMENT

    tensors = [
        _tensor_info("t.f32", TT_F32, [4], off_f32),
        _tensor_info("t.q8", TT_Q8_0, [32], off_q8),
    ]

    header = GGUF_MAGIC + struct.pack("<I", GGUF_VERSION)
    header += struct.pack("<Q", len(tensors))
    header += struct.pack("<Q", len(kvs))

    body = header + b"".join(kvs) + b"".join(tensors)
    pad = (-len(body)) % ALIGNMENT
    body += b"\x00" * pad
    assert len(body) % ALIGNMENT == 0

    data = bytearray()
    data += struct.pack("<4f", 1.0, 2.0, 3.0, 4.0)  # t.f32
    data += b"\x00" * (off_q8 - len(data))  # pad up to t.q8's offset
    data += struct.pack("<H", 0x3800)  # f16(0.5) scale
    data += struct.pack("<32b", *range(32))  # int8 0..31
    assert len(data) == off_q8 + q8_nbytes

    out = pathlib.Path(path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(body + bytes(data))


