# Op fixture container ("SURGEOPS") -- shared by tests/fixtures/ops.bin
# (numpy-generated, base scalar ops) and tests/fixtures/hybrid_ops.bin
# (mlx-generated, hybrid attention + gated DeltaNet ops).
#
# A fixture file is a flat, name-addressed bag of arrays. Everything is
# little-endian; the C reader is tests/test_ref_ops.c's fx_* helpers.
#
#   offset 0   char     magic[8]     = "SURGEOPS"
#   offset 8   uint32_t version      = 1
#   offset 12  uint32_t n_records
#   offset 16  record   dir[n_records]        (36 bytes each)
#   ...        char     names[]               (NUL-terminated, in dir order)
#   ...        (pad to 4)
#   ...        uint8_t  data[]                (each record 4-byte aligned)
#
# record (36 bytes, all uint32_t little-endian):
#   name_off    absolute byte offset of this record's NUL-terminated name
#   dtype       0 = f32, 1 = u16 (raw bf16 bit patterns), 2 = u8 (raw bytes)
#   n_dims      0..4; dims[i] for i >= n_dims are 0
#   dims[4]     row-major extents, slowest axis first
#   data_off    absolute byte offset of the payload (always 4-byte aligned)
#   nbytes      payload length in bytes (== prod(dims) * elem_size)
#
# Names are "<op>.<field>", e.g. "rmsnorm.x" / "rmsnorm.out". Scalars are
# stored as 1-element f32 arrays (e.g. "rmsnorm.eps") so the C side never
# has to parse anything but arrays.
# ======================================================================

FX_MAGIC = b"SURGEOPS"
FX_VERSION = 1
FX_F32, FX_U16, FX_U8 = 0, 1, 2
_FX_ELEM_SIZE = {FX_F32: 4, FX_U16: 2, FX_U8: 1}
_FX_DIR_ENTRY = 36


class FixtureWriter:
    """Accumulates named arrays and serializes them in the format above."""

    def __init__(self):
        self._records = []  # (name, dtype, dims, payload_bytes)

    def add(self, name, arr, dtype=FX_F32):
        import numpy as np

        if not isinstance(arr, np.ndarray):
            arr = np.asarray(arr)
        np_dtype = {FX_F32: np.float32, FX_U16: np.uint16, FX_U8: np.uint8}[dtype]
        arr = np.ascontiguousarray(arr, dtype=np_dtype)
        if arr.ndim > 4:
            raise ValueError(f"{name}: rank {arr.ndim} exceeds the format's 4")
        assert not any(r[0] == name for r in self._records), f"duplicate name {name}"
        self._records.append((name, dtype, list(arr.shape), arr.tobytes()))

    def add_scalar(self, name, value):
        self.add(name, [float(value)])

    def add_raw(self, name, payload, dims):
        assert not any(r[0] == name for r in self._records), f"duplicate name {name}"
        self._records.append((name, FX_U8, list(dims), bytes(payload)))

    def write(self, path):
        n = len(self._records)
        names_off = 16 + n * _FX_DIR_ENTRY

        name_blob = bytearray()
        name_offs = []
        for name, _, _, _ in self._records:
            name_offs.append(names_off + len(name_blob))
            name_blob += name.encode("ascii") + b"\x00"
        name_blob += b"\x00" * ((-len(name_blob)) % 4)

        data_off0 = names_off + len(name_blob)
        data_blob = bytearray()
        data_offs = []
        for _, dtype, dims, payload in self._records:
            pad = (-len(data_blob)) % 4
            data_blob += b"\x00" * pad
            data_offs.append(data_off0 + len(data_blob))
            elems = 1
            for d in dims:
                elems *= d
            assert len(payload) == elems * _FX_ELEM_SIZE[dtype], "payload size mismatch"
            data_blob += payload

        out = bytearray()
        out += FX_MAGIC
        out += struct.pack("<II", FX_VERSION, n)
        for (name, dtype, dims, payload), noff, doff in zip(
            self._records, name_offs, data_offs
        ):
            d4 = list(dims) + [0] * (4 - len(dims))
            out += struct.pack(
                "<IIIIIIIII",
                noff, dtype, len(dims), d4[0], d4[1], d4[2], d4[3], doff, len(payload),
            )
        assert len(out) == names_off, "directory size mismatch"
        out += name_blob
        assert len(out) == data_off0, "name blob size mismatch"
        out += data_blob

        p = pathlib.Path(path)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(bytes(out))
        print(f"wrote {path} ({n} records, {len(out)} bytes)")
        for name, dtype, dims, payload in self._records:
            print(f"    {name:44s} dtype={dtype} dims={dims}")


def _f32_to_bf16_array(x):
    """Round-to-nearest-even float32 -> bf16 bit patterns (uint16)."""
    import numpy as np

    bits = np.ascontiguousarray(x, dtype=np.float32).view(np.uint32).astype(np.uint64)
    bias = np.uint64(0x7FFF) + ((bits >> np.uint64(16)) & np.uint64(1))
    return ((bits + bias) >> np.uint64(16)).astype(np.uint16)


def _bf16_to_f32_array(u16):
    """Widen bf16 bit patterns back to float32 (what sg_ref_matvec_bf16 sees)."""
    import numpy as np

    return (np.ascontiguousarray(u16, dtype=np.uint16).astype(np.uint32) << 16).view(
        np.float32
    )


def _quantize_q8_0(row):
    """llama.cpp Q8_0 packing for one row: 32 values -> f16 scale + 32 int8.

    d = max|x| / 127; q = round(x / d). Returns (packed_bytes, dequantized).
    """
    import numpy as np

    row = np.ascontiguousarray(row, dtype=np.float32)
    assert row.size % 32 == 0, "Q8_0 rows must be a multiple of 32 long"
    packed = bytearray()
    deq = np.zeros_like(row)
    for b in range(row.size // 32):
        blk = row[b * 32:(b + 1) * 32]
        amax = float(np.abs(blk).max())
        d = amax / 127.0
        inv = (1.0 / d) if d != 0.0 else 0.0
        q = np.clip(np.rint(blk * inv), -127, 127).astype(np.int8)
        d16 = np.float16(d)
        packed += struct.pack("<H", int(np.float16(d16).view(np.uint16)))
        packed += q.tobytes()
        deq[b * 32:(b + 1) * 32] = np.float32(d16) * q.astype(np.float32)
    return bytes(packed), deq


def write_op_fixtures(out_path: str) -> None:
    """tests/fixtures/ops.bin: numpy reference values for the base scalar ops.

    Seeded (numpy default_rng(20260808)). Shapes follow the task brief:
      rmsnorm  n=64, eps=1e-6              -> rmsnorm.{x,w,eps,out}
      rope     head_dim=128, theta=1e6,    -> rope.{x,head_dim,theta,pos,
               pos in {0, 1, 4096}             out_pos0,out_pos1,out_pos4096}
      matvec   8x64, bf16 and Q8_0         -> matvec_bf16.{w,x,out,out_exact}
                                              matvec_q8.{w,x,out,out_exact}
      softmax  n=32, incl. -1e30 mask rows -> softmax.{x,out}
      swiglu   n=64                        -> swiglu.{gate,up,out}

    RoPE here is the FULL rotation (rope_dim == head_dim), half-split
    (non-interleaved) pairing: out[i] = x[i]cos - x[i+D/2]sin,
    out[i+D/2] = x[i]sin + x[i+D/2]cos, with theta_i = pos * base^(-2i/D).
    That convention was confirmed against mlx's nn.RoPE(traditional=False)
    -- see write_hybrid_op_fixtures's rope_partial records, which pin the
    same convention directly against mlx output.

    matvec_*.out is the plain f32 matvec (the "true" answer, tested to the
    brief's loose 3e-2 / 2e-2 quantization tolerances); matvec_*.out_exact
    is the matvec against the ROUNDED weights, i.e. the value the C op must
    produce bit-for-bit modulo summation order, tested to 1e-5. x is scaled
    by 1/sqrt(cols) so that the true result is O(1) and the brief's absolute
    tolerances are meaningful; the generator asserts both bounds hold before
    writing, so a regenerated fixture can never silently violate them.
    """
    import numpy as np

    rng = np.random.default_rng(20260808)
    fx = FixtureWriter()

    # --- rmsnorm: n=64, eps=1e-6 (mx.fast.rms_norm semantics:
    #     y = x * rsqrt(mean(x^2) + eps) * w).
    n = 64
    x = rng.standard_normal(n).astype(np.float32)
    w = rng.standard_normal(n).astype(np.float32)
    eps = 1e-6
    out = (x / np.sqrt(np.mean(x.astype(np.float64) ** 2) + eps) * w).astype(np.float32)
    fx.add("rmsnorm.x", x)
    fx.add("rmsnorm.w", w)
    fx.add_scalar("rmsnorm.eps", eps)
    fx.add("rmsnorm.out", out)

    # --- rope: head_dim=128, theta=1e6, full rotation, three positions.
    hd, theta = 128, 1.0e6
    rx = rng.standard_normal(hd).astype(np.float32)
    fx.add("rope.x", rx)
    fx.add_scalar("rope.head_dim", hd)
    fx.add_scalar("rope.theta", theta)
    for pos in (0, 1, 4096):
        ry = rx.astype(np.float64).copy()
        half = hd // 2
        i = np.arange(half, dtype=np.float64)
        ang = pos * (theta ** (-2.0 * i / hd))
        c, s = np.cos(ang), np.sin(ang)
        lo, hi = rx[:half].astype(np.float64), rx[half:].astype(np.float64)
        ry[:half] = lo * c - hi * s
        ry[half:] = lo * s + hi * c
        fx.add(f"rope.out_pos{pos}", ry.astype(np.float32))
    fx.add("rope.pos", np.array([0, 1, 4096], dtype=np.float32))

    # --- matvec: rows=8, cols=64, y = W x with W row-major [rows, cols].
    rows, cols = 8, 64
    mw = rng.standard_normal((rows, cols)).astype(np.float32)
    mx_in = (rng.standard_normal(cols) / np.sqrt(cols)).astype(np.float32)
    true_y = (mw.astype(np.float64) @ mx_in.astype(np.float64)).astype(np.float32)

    bf = _f32_to_bf16_array(mw)
    bf_y = (_bf16_to_f32_array(bf).astype(np.float64) @ mx_in.astype(np.float64))
    bf_err = float(np.abs(bf_y - true_y).max())
    assert bf_err < 3e-2, f"bf16 matvec fixture exceeds the 3e-2 brief bound: {bf_err}"
    fx.add("matvec_bf16.w", bf, dtype=FX_U16)
    fx.add("matvec_bf16.x", mx_in)
    fx.add("matvec_bf16.out", true_y)
    fx.add("matvec_bf16.out_exact", bf_y.astype(np.float32))

    packed = bytearray()
    q8_deq = np.zeros_like(mw)
    for r in range(rows):
        pb, dq = _quantize_q8_0(mw[r])
        packed += pb
        q8_deq[r] = dq
    q8_y = (q8_deq.astype(np.float64) @ mx_in.astype(np.float64))
    q8_err = float(np.abs(q8_y - true_y).max())
    assert q8_err < 2e-2, f"q8 matvec fixture exceeds the 2e-2 brief bound: {q8_err}"
    fx.add_raw("matvec_q8.w", packed, [rows, (cols // 32) * 34])
    fx.add("matvec_q8.x", mx_in)
    fx.add("matvec_q8.out", true_y)
    fx.add("matvec_q8.out_exact", q8_y.astype(np.float32))
    print(f"    (bf16 matvec max |err| {bf_err:.3e}, q8_0 matvec max |err| {q8_err:.3e})")

    # --- softmax: n=32, with large-negative masking values in it.
    sx = rng.standard_normal(32).astype(np.float32)
    sx[3] = -1e30
    sx[11] = -1e30
    sx[12] = -3.4e38  # near -FLT_MAX: exp() must not produce a NaN
    sx[20] = 12.0     # a large positive, to exercise the max subtraction
    sd = sx.astype(np.float64)
    se = np.exp(sd - sd.max())
    fx.add("softmax.x", sx)
    fx.add("softmax.out", (se / se.sum()).astype(np.float32))

    # --- swiglu: n=64, gate = silu(gate) * up.
    g = rng.standard_normal(64).astype(np.float32)
    u = rng.standard_normal(64).astype(np.float32)
    gd = g.astype(np.float64)
    fx.add("swiglu.gate", g)
    fx.add("swiglu.up", u)
    fx.add("swiglu.out", (gd / (1.0 + np.exp(-gd)) * u.astype(np.float64)).astype(np.float32))

    fx.write(out_path)


